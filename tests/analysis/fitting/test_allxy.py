"""Public ALLXY contracts against worked Reed-table examples, without lab inputs."""

from importlib import import_module

import numpy as np
import pytest

owner = import_module("zcu_tools.analysis.fitting")


@pytest.mark.parametrize(
    ("gates", "expected"),
    [
        (("I", "I"), 1.0),
        (("X180", "X180"), 0.9871997501756385),
        (("Y180", "Y180"), 0.9871997501756385),
        (("X180", "Y180"), 0.9927),
        (("Y180", "X180"), 0.9927),
        (("X90", "I"), -0.040513716694115404),
        (("Y90", "I"), -0.040513716694115404),
        (("I", "X90"), -0.040513716694115404),
        (("I", "Y90"), -0.040513716694115404),
        (("X90", "Y90"), 0.0616),
        (("Y90", "X90"), -0.0584),
        (("X90", "Y180"), 0.07),
        (("X180", "Y90"), 0.07),
        (("Y90", "X180"), 0.01),
        (("Y180", "X90"), 0.01),
        (("X90", "X180"), 0.12106028752058655),
        (("X180", "X90"), 0.12106028752058655),
        (("Y90", "Y180"), 0.12106028752058655),
        (("Y180", "Y90"), 0.12106028752058655),
        (("X180", "I"), -0.99635),
        (("Y180", "I"), -0.99635),
        (("I", "X180"), -0.99635),
        (("I", "Y180"), -0.99635),
        (("X90", "X90"), -0.995),
        (("Y90", "Y90"), -0.995),
    ],
)
def test_model_predicts_worked_gate_pairs(
    gates: tuple[str, str], expected: float
) -> None:
    # Reed thesis p.154, ep=0.04 rad and ed=-0.03. For example X90-Y90
    # gives 0.04**2 - 2*(-0.03) = 0.0616; these are literal worked values.
    assert owner.predict_state_with_error(gates, 0.04, -0.03) == pytest.approx(
        expected, rel=0.0, abs=1e-14
    )


def test_model_rejects_unsupported_pair() -> None:
    with pytest.raises(ValueError, match="Invalid gate pair"):
        owner.predict_state_with_error(("I", "Z90"), 0.0, 0.0)


@pytest.mark.parametrize("contrast", [1.8, -1.8])
def test_fitter_recovers_coherent_errors_and_predicts_worked_curve(
    contrast: float,
) -> None:
    # Independent worked table at ep=0.04, ed=-0.03, in caller-selected order.
    # It is deliberately neither imported from lab nor generated by the model.
    sequence = [
        ("I", "I"),
        ("X180", "X180"),
        ("Y180", "Y180"),
        ("X180", "Y180"),
        ("Y180", "X180"),
        ("X90", "I"),
        ("Y90", "I"),
        ("X90", "Y90"),
        ("Y90", "X90"),
        ("X90", "Y180"),
        ("Y90", "X180"),
        ("X180", "Y90"),
        ("Y180", "X90"),
        ("X90", "X180"),
        ("X180", "X90"),
        ("Y90", "Y180"),
        ("Y180", "Y90"),
        ("X180", "I"),
        ("Y180", "I"),
        ("X90", "X90"),
        ("Y90", "Y90"),
    ]
    states = np.array(
        [
            1.0,
            0.9871997501756385,
            0.9871997501756385,
            0.9927,
            0.9927,
            -0.040513716694115404,
            -0.040513716694115404,
            0.0616,
            -0.0584,
            0.07,
            0.01,
            0.07,
            0.01,
            0.12106028752058655,
            0.12106028752058655,
            0.12106028752058655,
            0.12106028752058655,
            -0.99635,
            -0.99635,
            -0.995,
            -0.995,
        ]
    )
    signals = 0.27 + 0.5 * contrast * states
    original = signals.copy()
    result = owner.fit_allxy_errors(sequence, signals)

    # Noiseless worked signals recover the known levels and coherent errors.
    tolerance = 1e-7
    assert result.amplitude_error == pytest.approx(
        0.04 / (np.pi / 2), rel=0.0, abs=tolerance
    )
    assert result.detune_param == pytest.approx(-0.03, rel=0.0, abs=tolerance)
    assert result.center == pytest.approx(0.27, rel=0.0, abs=tolerance)
    assert result.contrast == pytest.approx(contrast, rel=0.0, abs=tolerance)
    assert result.predict_signals.shape == signals.shape
    np.testing.assert_allclose(result.predict_signals, signals, rtol=0.0, atol=1e-7)
    expected_residual = np.sqrt(np.mean((signals - result.predict_signals) ** 2)) / (
        0.5 * abs(result.contrast)
    )
    assert result.residual_rms == pytest.approx(expected_residual, rel=0.0, abs=1e-14)
    assert result.residual_rms < 1e-7
    # Independent ideal staircase: zeroing either coherent error cannot meet
    # the parameter acceptance, and zeroing both misses the observed curve.
    ideal_states = np.array([1.0] * 5 + [0.0] * 12 + [-1.0] * 4)
    ideal_signals = 0.27 + 0.5 * contrast * ideal_states
    assert np.max(np.abs(signals - ideal_signals)) > 0.1
    # Worked absolute-deviation sums are 0.7744 for ep alone and
    # 0.25156908311930004 for ed alone, divided by the 21 selected pairs.
    assert result.power_err == pytest.approx(
        0.03687619047619048, rel=0.0, abs=tolerance
    )
    assert result.detune_err == pytest.approx(
        0.011979480148538097, rel=0.0, abs=tolerance
    )
    np.testing.assert_array_equal(signals, original)


@pytest.mark.parametrize("contrast", [1.8, -1.8])
def test_fitter_recovers_levels_outside_measured_extrema(contrast: float) -> None:
    sequence = [
        ("I", "I"),
        ("X180", "X180"),
        ("X180", "Y180"),
        ("X90", "I"),
        ("X90", "Y90"),
        ("Y90", "X90"),
        ("X90", "X180"),
        ("X180", "I"),
        ("X90", "X90"),
    ]
    center, ep, ed = 0.27, 0.1, 0.05
    signals = np.array(
        [
            center + 0.5 * contrast * owner.predict_state_with_error(pair, ep, ed)
            for pair in sequence
        ]
    )
    e_level = center - 0.5 * contrast
    assert e_level < signals.min() or e_level > signals.max()

    result = owner.fit_allxy_errors(sequence, signals)

    # Noiseless, identifiable data should recover all four parameters to 1e-7.
    # The true contrast exceeds measured ptp by 0.019125, well above tolerance.
    assert result.contrast == pytest.approx(contrast, rel=0.0, abs=1e-7)
    assert result.center == pytest.approx(center, rel=0.0, abs=1e-7)
    assert result.amplitude_error == pytest.approx(ep / (np.pi / 2), rel=0.0, abs=1e-7)
    assert result.detune_param == pytest.approx(ed, rel=0.0, abs=1e-7)


def test_fitter_recovers_ideal_staircase_at_tight_tolerance() -> None:
    sequence = [
        ("I", "I"),
        ("X90", "I"),
        ("X90", "Y90"),
        ("Y90", "X90"),
        ("X90", "Y180"),
        ("Y90", "X180"),
        ("X90", "X180"),
        ("X180", "I"),
        ("X90", "X90"),
    ]
    signals = np.array([1.17, 0.27, 0.27, 0.27, 0.27, 0.27, 0.27, -0.63, -0.63])
    result = owner.fit_allxy_errors(sequence, signals)
    assert result.amplitude_error == pytest.approx(0.0, abs=1e-8)
    assert result.detune_param == pytest.approx(0.0, abs=1e-8)
    assert result.center == pytest.approx(0.27, rel=0.0, abs=1e-8)
    assert result.contrast == pytest.approx(1.8, rel=0.0, abs=1e-8)
    assert result.power_err == pytest.approx(0.0, abs=1e-8)
    assert result.detune_err == pytest.approx(0.0, abs=1e-8)
    assert result.residual_rms < 1e-8
    np.testing.assert_allclose(result.predict_signals, signals, rtol=0.0, atol=1e-8)
